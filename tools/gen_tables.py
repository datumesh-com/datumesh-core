#!/usr/bin/env python3
"""Generate crates/datumesh-core/src/tables.rs from the spec's data files.

Reads spec/units.md (the fenced blocks tagged units-currency, units-physical, units-ratio)
and spec/tools/unicode-15.1-assigned.txt. Standard library only. Run from the repository root:

    python3 tools/gen_tables.py

The test `tables_match_spec` (crates/datumesh-core/tests/tables.rs) checks that the
committed output equals what the spec files say.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UNITS = os.path.join(ROOT, "spec", "units.md")
ASSIGNED = os.path.join(ROOT, "spec", "tools", "unicode-15.1-assigned.txt")
OUT = os.path.join(ROOT, "crates", "datumesh-core", "src", "tables.rs")


def unit_blocks():
    blocks = {"units-currency": [], "units-physical": [], "units-ratio": []}
    text = open(UNITS, encoding="utf-8").read()
    for tag, body in re.findall(r"^```(units-[a-z]+)\n(.*?)^```", text, re.S | re.M):
        if tag not in blocks:
            sys.exit("unknown units block: " + tag)
        blocks[tag].extend(body.split())
    return blocks


def ranges():
    out = []
    for line in open(ASSIGNED, encoding="ascii"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        a, b = line.split("..")
        out.append((int(a, 16), int(b, 16)))
    return out


def rust_strs(name, doc, items):
    body = "".join('    "%s",\n' % s for s in items)
    return "/// %s\npub(crate) const %s: &[&str] = &[\n%s];\n" % (doc, name, body)


def main():
    b = unit_blocks()
    r = ranges()
    parts = [
        "// @generated by tools/gen_tables.py from spec/units.md and\n"
        "// spec/tools/unicode-15.1-assigned.txt. Do not edit by hand.\n\n",
        rust_strs("CURRENCIES", "Currency codes, `units.md` 2.1, in file order.", b["units-currency"]),
        "\n",
        rust_strs("PHYSICAL", "Physical units, `units.md` 2.2, in file order.", b["units-physical"]),
        "\n",
        rust_strs("RATIOS", "Ratios and counts, `units.md` 2.3, in file order.", b["units-ratio"]),
        "\n/// Code points assigned in Unicode 15.1 (General_Category != Cn), inclusive ranges.\n",
        "pub(crate) const ASSIGNED: &[(u32, u32)] = &[\n",
        "".join("    (0x%04X, 0x%04X),\n" % x for x in r),
        "];\n",
    ]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(parts))


if __name__ == "__main__":
    main()
